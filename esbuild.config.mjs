import esbuild from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { builtinModules } from "node:module";

const production = process.argv[2] === "production";
const context = await esbuild.context({
	plugins: [{ name: "shared-appearance-defaults", setup(build) {
		build.onLoad({ filter: /appearance-tokens\.json$/ }, async args => ({
			contents: await readFile(args.path, "utf8"), loader: "json", watchFiles: [path.resolve("styles.css")],
		}));
		build.onEnd(async result => {
			if (result.errors.length) return;
			const strengths = JSON.parse(await readFile("src/appearance-tokens.json", "utf8"));
			const old = await readFile("styles.css", "utf8");
			const body = old.replace(/^\/\*[\s\S]*?\*\/\s*:root\s*\{[^}]*\}\s*/, "");
			const header = "/* Generated defaults from src/appearance-tokens.json; stylesheet body remains authored here. */\n:root {\n"
				+ Object.entries(strengths).map(([key, value]) => "\t--ft-default-" + key + "-strength: " + value + "%;").join("\n") + "\n}\n";
			if (header + body !== old) await writeFile("styles.css", header + body);
		});
	} }],
	banner: { js: "/* Folder Toolkit — generated by esbuild. */" },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian", "electron", ...builtinModules],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: production,
});
if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
